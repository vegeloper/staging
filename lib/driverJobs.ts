export function getDriverJob(id: string) {
  return driverJobs.find((job) => job.id === id);
}

export function getDriverJobCards() {
  return driverJobs.map(
    ({
      id,
      city,
      driverCount,
      title,
      description,
    }) => ({
      id,
      city,
      driverCount,
      title,
      description,
    }),
  );
}